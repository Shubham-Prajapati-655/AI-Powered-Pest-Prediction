"""
Step 3 & Step 4: Preprocessing and Stratified Train/Test Split Module.
Implements leak-free sklearn Pipeline & ColumnTransformer.
Ensures preprocessors and scalers are fitted ONLY on training split.
"""
import os
import sys
import json
import joblib
import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OrdinalEncoder, StandardScaler, LabelEncoder
from sklearn.impute import SimpleImputer

# Add root directory to sys.path
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from src.pipeline_config import (
    CLEAN_DATASET_PATH,
    ARTIFACTS_DIR,
    MODELS_DIR,
    CATEGORICAL_FEATURES,
    NUMERICAL_FEATURES,
    ENGINEERED_FEATURES,
    ALL_FEATURE_COLUMNS,
    TARGET_PEST,
    TARGET_RISK,
    RANDOM_STATE
)
from utils.logger import setup_logger

logger = setup_logger("preprocessor", "preprocessing.log")

def build_feature_preprocessor():
    """
    Constructs an sklearn ColumnTransformer pipeline:
    - Numerical: SimpleImputer(strategy='median') + StandardScaler()
    - Categorical: SimpleImputer(strategy='most_frequent') + OrdinalEncoder()
    """
    num_cols = NUMERICAL_FEATURES + ENGINEERED_FEATURES
    cat_cols = CATEGORICAL_FEATURES

    numeric_transformer = Pipeline(steps=[
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler())
    ])

    categorical_transformer = Pipeline(steps=[
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("encoder", OrdinalEncoder(handle_unknown="use_encoded_value", unknown_value=-1))
    ])

    preprocessor = ColumnTransformer(
        transformers=[
            ("num", numeric_transformer, num_cols),
            ("cat", categorical_transformer, cat_cols)
        ],
        remainder="drop"
    )

    return preprocessor, num_cols, cat_cols

def prepare_stratified_splits(
    dataset_path: str = CLEAN_DATASET_PATH,
    test_size: float = 0.20,
    save_artifacts: bool = True
):
    """
    Loads clean dataset, performs stratified split based on target classes,
    fits ColumnTransformer strictly on X_train, transforms X_test,
    and serializes preprocessor artifacts.
    """
    logger.info("=========================================================")
    logger.info("STEP 3 & 4: STRATIFIED SPLIT & LEAK-FREE PREPROCESSING")
    logger.info("=========================================================")

    if not os.path.exists(dataset_path):
        raise FileNotFoundError(f"Clean dataset not found at {dataset_path}. Run sanitizer first.")

    df = pd.read_csv(dataset_path)
    logger.info(f"Loaded clean dataset: {df.shape[0]:,} rows, {df.shape[1]} columns.")

    X = df[ALL_FEATURE_COLUMNS].copy()
    y_pest_raw = df[TARGET_PEST].copy()
    y_risk_raw = df[TARGET_RISK].copy()

    # Encode target labels
    le_pest = LabelEncoder()
    y_pest = le_pest.fit_transform(y_pest_raw)

    le_risk = LabelEncoder()
    y_risk = le_risk.fit_transform(y_risk_raw)

    # Joint stratification tag to preserve distribution of both Pest and Risk
    strat_key = y_pest_raw.astype(str) + "_" + y_risk_raw.astype(str)
    # Check rare combinations (<2 samples) to fallback safely to pest-only stratification if needed
    val_counts = strat_key.value_counts()
    if (val_counts < 2).any():
        logger.info("Some joint target combinations have <2 samples. Using Target 1 (Pest_Name) for exact stratification.")
        strat_vector = y_pest
    else:
        logger.info("Stratifying on joint (Pest_Name + Risk_Level) distribution.")
        strat_vector = strat_key

    X_train_df, X_test_df, y_train_pest, y_test_pest, y_train_risk, y_test_risk = train_test_split(
        X, y_pest, y_risk,
        test_size=test_size,
        random_state=RANDOM_STATE,
        stratify=strat_vector
    )

    logger.info(f"Train/Test split complete: Train={len(X_train_df):,} ({1-test_size:.0%}), Test={len(X_test_df):,} ({test_size:.0%})")

    # Fit preprocessor ONLY on X_train_df
    logger.info("Fitting ColumnTransformer STRICTLY on X_train (Zero Test Leakage)...")
    preprocessor, num_cols, cat_cols = build_feature_preprocessor()
    X_train_transformed = preprocessor.fit_transform(X_train_df)
    X_test_transformed = preprocessor.transform(X_test_df)

    # Feature names in the exact order generated by ColumnTransformer:
    # First all numeric/engineered columns, then all categorical columns
    transformed_feature_names = num_cols + cat_cols

    if save_artifacts:
        os.makedirs(ARTIFACTS_DIR, exist_ok=True)
        os.makedirs(MODELS_DIR, exist_ok=True)

        logger.info("Saving preprocessing artifacts...")
        # 1. Full Preprocessor
        joblib.dump(preprocessor, os.path.join(ARTIFACTS_DIR, "preprocessor.pkl"))
        joblib.dump(preprocessor, os.path.join(MODELS_DIR, "preprocessor.pkl"))

        # 2. Individual Encoder & Scaler for reference
        num_pipeline = preprocessor.named_transformers_["num"]
        scaler = num_pipeline.named_steps["scaler"]
        joblib.dump(scaler, os.path.join(ARTIFACTS_DIR, "scaler.pkl"))

        cat_pipeline = preprocessor.named_transformers_["cat"]
        encoder = cat_pipeline.named_steps["encoder"]
        joblib.dump(encoder, os.path.join(ARTIFACTS_DIR, "encoder.pkl"))

        # 3. Label Encoders
        joblib.dump(le_pest, os.path.join(ARTIFACTS_DIR, "label_encoder_pest.pkl"))
        joblib.dump(le_pest, os.path.join(MODELS_DIR, "label_encoder_pest.pkl"))
        joblib.dump(le_risk, os.path.join(ARTIFACTS_DIR, "label_encoder_risk.pkl"))
        joblib.dump(le_risk, os.path.join(MODELS_DIR, "label_encoder_risk.pkl"))

        # 4. Feature Columns JSON
        feature_metadata = {
            "all_features": ALL_FEATURE_COLUMNS,
            "categorical_features": cat_cols,
            "numerical_features": NUMERICAL_FEATURES,
            "engineered_features": ENGINEERED_FEATURES,
            "transformed_feature_order": transformed_feature_names,
            "target_pest": TARGET_PEST,
            "target_risk": TARGET_RISK,
            "pest_classes": le_pest.classes_.tolist(),
            "risk_classes": le_risk.classes_.tolist(),
            "num_features_total": len(transformed_feature_names)
        }
        with open(os.path.join(ARTIFACTS_DIR, "feature_columns.json"), "w", encoding="utf-8") as f:
            json.dump(feature_metadata, f, indent=2)

        logger.info("All preprocessing artifacts saved to 'artifacts/' and 'models/'.")

    return {
        "X_train_df": X_train_df,
        "X_test_df": X_test_df,
        "X_train": X_train_transformed,
        "X_test": X_test_transformed,
        "y_train_pest": y_train_pest,
        "y_test_pest": y_test_pest,
        "y_train_risk": y_train_risk,
        "y_test_risk": y_test_risk,
        "le_pest": le_pest,
        "le_risk": le_risk,
        "preprocessor": preprocessor,
        "feature_names": transformed_feature_names
    }

if __name__ == "__main__":
    prepare_stratified_splits()
